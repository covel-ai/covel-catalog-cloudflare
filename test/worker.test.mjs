  await h.policy(policy([],++sequence));
  const changed=entry({commitSha:'d'.repeat(40),sourceTreeHash:'e'.repeat(64)});await h.publish(catalog([changed],{generatedAt:stamp(1)}));
  await h.policy(policy([{id:'old-only',repositoryId:42,commitSha:entry().commitSha,reason:'old version withdrawn',createdAt:new Date().toISOString()}],++sequence));
  assert.equal((await h.raw('/v1/catalog')).data.total,1);
  assert.equal((await h.mf.dispatchFetch(ready.data.url)).status,410);
  await h.db.prepare('UPDATE policies SET expires=0 WHERE sequence=?').bind(sequence).run();
  assert.equal((await h.raw('/v1/catalog')).status,503);assert.equal((await h.raw('/v1/downloads','POST',input)).status,503);
